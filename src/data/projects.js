/** @type {Project[]} */
export const PROJECTS = RAW.map((p) => ({
  ...p,
  stars: p.repo ? (BREAKOUT[p.repo]?.stars ?? STARS[p.repo] ?? null) : null,
  url: p.url ?? `https://github.com/${p.repo}`,
  breakout: !!(p.repo && BREAKOUT[p.repo]),
}));

/** '118k' -> 118000, '7.7k' -> 7700, '1.2M' -> 1200000, null -> 0. */
export function starCount(s) {
  if (!s) return 0;
  const m = /^([\d.]+)\s*([kKmM]?)$/.exec(String(s).trim());
  if (!m) return 0;
  return Math.round(parseFloat(m[1]) * ({ k: 1e3, m: 1e6 }[m[2].toLowerCase()] ?? 1));
}

export const projectById = (id) => PROJECTS.find((p) => p.id === id);
